"""Embed a built web bundle (dist/) into crates/bagz-web/src/bundle.rs as Rust constants.

pyCrust keeps tracked source to Python, C and Rust. The React/TypeScript UI source lives on the
`legacy-ts` branch; its built output is stored here byte for byte, with a SHA-256 per file.
Usage: python3 scripts/embed_web.py <dist-dir>
"""
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TYPES = {".html": "text/html; charset=utf-8", ".js": "application/javascript; charset=utf-8",
         ".css": "text/css; charset=utf-8", ".svg": "image/svg+xml"}


def raw(s: str) -> str:
    n = 1
    while ('"' + "#" * n) in s:
        n += 1
    return "r" + "#" * n + '"' + s + '"' + "#" * n


def main(dist: Path):
    files = sorted(p for p in dist.rglob("*") if p.is_file() and p.suffix in TYPES)
    lines = ["// @generated by scripts/embed_web.py from the built web bundle. Do not edit by hand.",
             "// (path, content type, sha256, body)",
             "pub static FILES: &[(&str, &str, &str, &str)] = &["]
    for p in files:
        body = p.read_text(encoding="utf-8")
        rel = "/" + p.relative_to(dist).as_posix()
        sha = hashlib.sha256(body.encode()).hexdigest()
        lines.append(f'    ("{rel}", "{TYPES[p.suffix]}", "{sha}", {raw(body)}),')
    lines.append("];")
    out = ROOT / "crates" / "bagz-web" / "src" / "bundle.rs"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"embedded {len(files)} files into {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
